package com.Arrays;

public class Array08Object {
	int id;
	String name;
	int age;
	double salary;
	
	
	
	
	@Override
	public String toString() {
		return "Array08Object [id=" + id + ", name=" + name + ", age=" + age + ", salary=" + salary + "]";
	}




	public Array08Object(int id, String name, int age, double salary) {
		super();
		this.id = id;
		this.name = name;
		this.age = age;
		this.salary = salary;
	}
	
	
	

}
